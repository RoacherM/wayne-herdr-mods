// Bundle the WebView terminal (xterm.js + term/term.js + css) into one HTML string the app embeds:
// src/term-html.ts. No network needed to show a terminal.  node ios/build-term.mjs
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const js = (await build({ entryPoints: [join(here, 'term/term.js')], bundle: true, minify: true, format: 'iife', write: false, target: 'safari15' })).outputFiles[0].text;
const css = await readFile(join(here, '../node_modules/@xterm/xterm/css/xterm.css'), 'utf8');
const html = `<!doctype html><html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no">
<style>${css}
html,body{margin:0;height:100%;overflow:hidden;-webkit-text-size-adjust:100%}
#vp{position:absolute;inset:0;overflow:auto;-webkit-overflow-scrolling:touch;padding:4px 6px;box-sizing:border-box}
#host{width:max-content}
</style></head><body><div id="vp"><div id="host"></div></div>
<script>${js.replace(/<\/script/gi, '<\\/script')}</script></body></html>`;
await writeFile(join(here, 'src/term-html.ts'), `// Generated by build-term.mjs — do not edit.\nexport const TERM_HTML = ${JSON.stringify(html)};\n`);
console.log(`term-html.ts ${(html.length / 1024).toFixed(0)} KB`);
